#include <stddef.h>
#include <stdint.h>
#include <stdlib.h>
#include <string.h>
#include "fa_c.h"
#include "_printf.h"

static
t_fa_c
	*pointer_itoa(
uintptr_t n,
struct s_printf_argument *format
)
{
	const static char	radix[] = "0123456789abcdef";
	char				buf[100];
	int					index;

	if (!n)
	{
		format->null = true;
		return (fa_c_from_str("(nil)"));
	}
	buf[99] = 0;
	buf[98] = radix[n % 16];
	index = 97;
	if (!n)
		format->null = true;
	while (n / 16)
	{
		n /= 16;
		buf[index--] = radix[n % 16];
	}
	buf[index--] = 'x';
	buf[index--] = '0';
	return (fa_c_from_str(&buf[index + 1]));
}

t_fa_c
	*specifier_pointer(
va_list arg,
unsigned int current_len,
struct s_printf_argument *format
)
{
	(void)current_len;
	if (format->length != NONE)
		return (NULL);
	return (pointer_itoa(va_arg(arg, uintptr_t), format));
}
