#include <string.h>
#include "fa_c.h"

t_fa_c
	*handle_raw(
const char **format
)
{
	t_fa_c				*out;
	const char *const	next_percent = strchr(*format, '%');

	if (next_percent)
		out = calloc_fa_c(next_percent - *format);
	else
		out = calloc_fa_c(strlen(*format));
	if (!out)
		return (NULL);
	memcpy(out->buf, *format, out->len);
	*format += out->len;
	return (out);
}
