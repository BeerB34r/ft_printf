#include <stddef.h>
#include "fa_c.h"
#include "_printf.h"

int
	handle_width(
t_fa_c **out,
struct s_printf_argument format
)
{
	static int (*const	specifiers[])(t_fa_c **, struct s_printf_argument) = {
		NULL,
		NULL,
		NULL,
		NULL,
		NULL,
		NULL,
		NULL,
		NULL,
		NULL,
		NULL,
		NULL,
		NULL,
		NULL
	};

	if (specifiers[format.specifier])
		return (specifiers[format.specifier](out, format));
	return (0);
}
