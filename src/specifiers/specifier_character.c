#include <stddef.h>
#include "fa_c.h"
#include "_printf.h"

t_fa_c
	*specifier_character(
va_list args,
unsigned int current_len,
struct s_printf_argument *format
)
{
	t_fa_c	*out;

	(void)current_len;
	if (format->length != NONE)
		return (NULL);
	out = calloc_fa_c(1);
	if (out)
		out->buf[0] = (char)va_arg(args, int);
	return (out);
}
